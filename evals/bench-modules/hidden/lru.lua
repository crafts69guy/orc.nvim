return function(api, t)
	t.test("lru recency and eviction", function()
		local cache = api.new(2)
		t.eq(cache:get("none"), nil)
		t.eq(cache:set("a", 1), cache)
		cache:set("b", 2)
		t.eq(cache:get("a"), 1)
		cache:set("c", 3)
		t.eq(cache:has("b"), false)
		t.eq(cache:has("a"), true)
		t.eq(cache.size, 2)
		cache:set("a", 4)
		t.eq(cache:get("a"), 4)
		cache:set("d", 5)
		t.eq(cache:has("c"), false)
	end)
	t.test("lru has does not touch and delete handles every list position", function()
		local cache = api.new(3)
		cache:set("a", 1):set("b", 2):set("c", 3)
		t.eq(cache:has("a"), true)
		cache:set("d", 4)
		t.eq(cache:has("a"), false)
		t.eq(cache:delete("c"), true)
		t.eq(cache:delete("b"), true)
		t.eq(cache:delete("d"), true)
		t.eq(cache:delete("missing"), false)
		t.eq(cache.size, 0)
		cache:set("fresh", 1)
		t.eq(cache:get("fresh"), 1)
	end)
	t.test("lru nil NaN zero and object identity", function()
		local cache, a, b = api.new(8), {}, {}
		cache:set(nil, nil):set(0 / 0, "nan"):set(-0, "zero"):set(a, a):set(b, b)
		t.eq(cache:has(nil), true)
		t.eq(cache:get(nil), nil)
		t.eq(cache:get(0 / 0), "nan")
		t.eq(cache:get(0), "zero")
		t.eq(cache:get(a), a)
		t.eq(cache:get(b), b)
		t.eq(cache:delete(nil), true)
		t.eq(cache:has(nil), false)
	end)
	t.test("lru capacity one updates and size is read-only", function()
		local cache = api.new(1)
		cache:set("a", nil):set("a", 2):set("b", 3)
		t.eq(cache:get("a"), nil)
		t.eq(cache.size, 1)
		t.eq(cache.unknown, nil)
		t.error("TypeError", function()
			cache.size = 4
		end)
	end)
	for _, capacity in ipairs({ 0, -1, 1.5, math.huge, "2", false, 0 / 0 }) do
		t.test("lru invalid capacity " .. tostring(capacity), function()
			t.error("RangeError", function()
				api.new(capacity)
			end)
		end)
	end
end

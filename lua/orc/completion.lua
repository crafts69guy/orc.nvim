local M = {}

---Fish completions are printed, never installed implicitly.
---@return string
function M.fish()
	local lines = { "# Generated by orc completion fish" }
	for name, description in pairs({
		claude = "Run Claude Code",
		codex = "Run Codex",
		wt = "Manage worktrees",
		pane = "Manage Rex workers",
		status = "Show tasks",
		doctor = "Check prerequisites",
		context = "Audit context",
		inkdrop = "Sync notes",
		["inkdrop-mcp"] = "Manage opt-in shared Inkdrop MCP",
		update = "Update Git installation",
		eval = "Run evaluations",
		completion = "Print completions",
	}) do
		lines[#lines + 1] = "complete -c orc -n __fish_use_subcommand -a "
			.. name
			.. " -d '"
			.. description
			.. "'"
	end
	table.sort(lines)
	for _, name in ipairs({ "claude", "codex" }) do
		for _, flag in ipairs({ "yolo", "panes", "no-panes", "pair" }) do
			lines[#lines + 1] = "complete -c orc -n '__fish_seen_subcommand_from "
				.. name
				.. "' -l "
				.. flag
		end
		for _, flag in ipairs({ "level", "wt", "base" }) do
			lines[#lines + 1] = "complete -c orc -n '__fish_seen_subcommand_from "
				.. name
				.. "' -l "
				.. flag
				.. " -r"
		end
		lines[#lines + 1] = "complete -c orc -n '__fish_seen_subcommand_from "
			.. name
			.. "' -l inkdrop-mcp -x -a 'inherit shared'"
	end
	for _, pair in ipairs({
		{ "wt", "new merge remove list session" },
		{ "pane", "start wait prompt close prune" },
		{ "inkdrop", "init inbox claim push pull lessons" },
		{
			"inkdrop-mcp",
			"install start stop restart status enable disable migrate rollback uninstall",
		},
		{ "completion", "fish" },
	}) do
		lines[#lines + 1] = "complete -c orc -n '__fish_seen_subcommand_from "
			.. pair[1]
			.. "' -a '"
			.. pair[2]
			.. "'"
	end
	for _, flag in ipairs({ "proxy", "node", "backend", "port", "credentials", "provider" }) do
		lines[#lines + 1] = "complete -c orc -n '__fish_seen_subcommand_from inkdrop-mcp' -l "
			.. flag
			.. " -r"
	end
	lines[#lines + 1] = "complete -c orc -n '__fish_seen_subcommand_from inkdrop-mcp' -l apply"
	lines[#lines + 1] =
		"complete -c orc -n '__fish_seen_subcommand_from pane' -l role -x -a 'implementer scoper'"
	for _, flag in ipairs({
		"path",
		"brief",
		"kind",
		"timeout",
		"text",
		"file",
		"message",
		"base",
		"book",
		"parent",
		"scope",
	}) do
		lines[#lines + 1] = "complete -c orc -l " .. flag .. " -r"
	end
	for _, flag in ipairs({
		"json",
		"yes",
		"here",
		"create",
		"move",
		"done",
		"help",
		"version",
		"bench",
	}) do
		lines[#lines + 1] = "complete -c orc -l " .. flag
	end
	return table.concat(lines, "\n") .. "\n"
end

return M
